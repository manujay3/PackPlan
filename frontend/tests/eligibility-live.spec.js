import { test, expect } from '@playwright/test'

test('checks real stored rules through the frontend proxy', async ({ page }) => {
  test.skip(process.env.PACKPLAN_LIVE_E2E !== 'true', 'Requires the local backend and imported Neo4j sample')
  await page.goto('/eligibility')
  await expect(page.getByLabel('Target course')).toHaveValue('csc-216-2026-2027')
  await page.getByRole('button', { name: '+ Add completed attempt' }).click()
  const attempt = page.locator('.attempt-row')
  await attempt.getByLabel('Course', { exact: true }).selectOption('csc-116-2026-2027')
  await attempt.getByLabel('Grade or outcome').selectOption('C')
  await attempt.getByLabel('Earned credit?').selectOption('true')
  await page.getByRole('checkbox', { name: /CSC 217/ }).check()
  await page.getByRole('button', { name: 'Check course requirements', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Stored rule satisfied' })).toBeVisible()
  await attempt.getByLabel('Grade or outcome').selectOption('C_MINUS')
  await page.getByRole('button', { name: 'Check course requirements', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Requirements not met' })).toBeVisible()
  await page.getByRole('button', { name: 'Remove attempt 1' }).click()
  await page.getByLabel('Target course').selectOption('csc-116-2026-2027')
  await page.getByRole('checkbox', { name: /CSC 217/ }).uncheck()
  await page.getByRole('checkbox', { name: /E 115/ }).check()
  await page.getByRole('checkbox', { name: /MA 141/ }).check()
  await page.getByRole('button', { name: 'Check course requirements', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Manual review needed' })).toBeVisible()
  await expect(page.locator('.root-conditions')).toContainText('Most seats reserved')
  await page.getByLabel('Target course').selectOption('ma-141-2026-2027')
  await page.getByRole('button', { name: 'Check course requirements', exact: true }).click()
  await expect(page.getByText('No stored rule available', { exact: true })).toBeVisible()
})

test('validates every proposed course through the real semester endpoint', async ({ page }) => {
  test.skip(process.env.PACKPLAN_LIVE_E2E !== 'true', 'Requires the local backend and imported Neo4j sample')
  await page.goto('/semester')
  await page.getByLabel('Your semester credit cap').fill('15')
  await page.getByRole('button', { name: '+ Add completed attempt' }).click()
  const attempt = page.locator('.attempt-row')
  await attempt.getByLabel('Course', { exact: true }).selectOption('csc-116-2026-2027')
  await attempt.getByLabel('Grade or outcome').selectOption('C')
  await attempt.getByLabel('Earned credit?').selectOption('true')
  await page.getByRole('checkbox', { name: /CSC 216/ }).check()
  await page.getByRole('checkbox', { name: /CSC 217/ }).check()
  await page.getByRole('button', { name: 'Check semester requirements', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Stored semester rules satisfied' })).toBeVisible()
  await expect(page.locator('.semester-course-result')).toHaveCount(2)
  await page.getByLabel('Your semester credit cap').fill('3')
  await page.getByRole('button', { name: 'Check semester requirements', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Semester has blockers' })).toBeVisible()
  await expect(page.locator('.credit-load')).toContainText('Over cap')
  await page.getByLabel('Your semester credit cap').fill('4')
  await page.getByRole('button', { name: 'Check semester requirements', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Stored semester rules satisfied' })).toBeVisible()
  await expect(page.locator('.credit-load')).toContainText('4 credits · Cap: 4')
  await page.getByLabel('Your semester credit cap').fill('15')
  await page.getByRole('checkbox', { name: /CSC 217/ }).uncheck()
  await page.getByRole('button', { name: 'Check semester requirements', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Semester has blockers' })).toBeVisible()
  await page.getByRole('checkbox', { name: /CSC 217/ }).check()
  await page.getByRole('checkbox', { name: /MA 141/ }).check()
  await page.getByRole('button', { name: 'Check semester requirements', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Semester needs review' })).toBeVisible()
  await expect(page.getByText('No stored rule available', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Remove attempt 1' }).click()
  await page.getByRole('button', { name: 'Check semester requirements', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Semester has blockers' })).toBeVisible()
})
